import assert from "node:assert/strict";
import {POKEMON,RARITIES,DEFAULT_RARITY_CHANCES,rollRunRoster,getOriginalTemplate} from "./pokemon.js";
import {ORIGINAL_COMBAT_TEMPLATES} from "./templates.js";
assert.equal(ORIGINAL_COMBAT_TEMPLATES.length,233);
assert.equal(new Set(ORIGINAL_COMBAT_TEMPLATES.map(t=>t.id)).size,233);
assert.equal(RARITIES.length,5);
assert.deepEqual(DEFAULT_RARITY_CHANCES,{scrap:100,rough:0,framed:0,opus:0,masterpiece:0});
assert.equal(POKEMON.length,29);
assert.ok(POKEMON.every(p=>p.boss||getOriginalTemplate(p)?.rarity===p.rarity));
const initial=rollRunRoster({rng:()=>.5});
assert.ok(initial.length>0);
assert.ok(initial.every(p=>p.rarity==="scrap"&&!p.evolved&&!p.boss));
const everyone=rollRunRoster({rng:()=>0,chances:Object.fromEntries(RARITIES.map(r=>[r,100]))});
assert.ok(everyone.every(p=>!p.evolved&&!p.boss));
assert.ok(!everyone.some(p=>[25,35,212,1024].includes(p.dex)));
const nobody=rollRunRoster({rng:()=>.5,chances:Object.fromEntries(RARITIES.map(r=>[r,0]))});
assert.equal(nobody.length,0);
const selected=rollRunRoster({rng:()=>.5,chances:{scrap:100,rough:50,framed:0,opus:0,masterpiece:0}});
assert.ok(selected.every(p=>p.rarity==="scrap"));
const selectedAll=rollRunRoster({rng:()=>.49,chances:{scrap:100,rough:50,framed:0,opus:0,masterpiece:0}});
assert.ok(selectedAll.some(p=>p.rarity==="rough"));
console.log("PokéLoop Pokémon roster tests passed");
